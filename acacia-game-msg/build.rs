use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let proto_dir = PathBuf::from("proto");
    let out_dir = PathBuf::from("generated");
    std::fs::create_dir_all(&out_dir)?;

    let mut file_descriptor_set = prost_types::FileDescriptorSet { file: Vec::new() };
    for entry in std::fs::read_dir(&proto_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("pb") {
            let bytes = std::fs::read(&path)?;
            let fd: prost_types::FileDescriptorProto = <prost_types::FileDescriptorProto as prost::Message>::decode(bytes.as_slice())?;
            file_descriptor_set.file.push(fd);
        }
    }

    let mut config = prost_build::Config::new();
    config.out_dir(&out_dir);
    config.compile_fds(file_descriptor_set)?;

    let mut include_content = String::from("// This file is @generated by acacia-game-msg.\n");
    let mut entries: Vec<_> = std::fs::read_dir(&out_dir)?.filter_map(|e| e.ok()).collect();
    entries.sort_by_key(|e| e.file_name());

    for entry in entries {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            let file_name = path.file_name().unwrap().to_str().unwrap();
            if file_name != "_include.rs" {
                let mod_name = file_name.trim_end_matches(".rs").replace('.', "_");
                include_content.push_str(&format!("pub mod {mod_name} {{\n    include!(\"{file_name}\");\n}}\n"));
            }
        }
    }
    std::fs::write(out_dir.join("_include.rs"), include_content)?;

    Ok(())
}
